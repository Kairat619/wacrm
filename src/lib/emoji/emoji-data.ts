/**
 * Curated emoji set for the inbox composer picker.
 *
 * Deliberately hand-rolled instead of pulling in emoji-mart / the full
 * Unicode CLDR dataset: those ship 1–2 MB of JSON into the client bundle
 * for a picker that agents use to drop a 👍 into a reply. This list covers
 * the emoji that actually show up in customer chats, and every glyph here
 * renders on WhatsApp (Unicode 12 and below, no ZWJ sequences beyond the
 * common family/profession ones we skip entirely).
 *
 * `keywords` drive the search box and are English-only — the category
 * tabs are the localized affordance for non-English agents.
 */

export interface EmojiEntry {
  /** The emoji glyph itself — inserted verbatim into the composer. */
  char: string;
  /** Lowercase, space-separated search terms (English). */
  keywords: string;
}

export type EmojiCategoryId =
  | 'smileys'
  | 'gestures'
