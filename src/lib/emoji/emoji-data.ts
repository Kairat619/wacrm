/** Flat lookup used by the search box. */
export const ALL_EMOJIS: readonly EmojiEntry[] = EMOJI_CATEGORIES.flatMap(
  (c) => c.emojis
);

/**
 * Substring match over glyph + keywords. Kept dumb on purpose: the list is
 * ~500 entries, so filtering on every keystroke costs nothing.
 */
export function searchEmojis(query: string): readonly EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return ALL_EMOJIS;
  return ALL_EMOJIS.filter(
    (entry) => entry.char === q || entry.keywords.includes(q)
  );
}
